/** Hat diese Waffe eine Wirkung ueber Schaden und Flaeche hinaus? */
export function hasSpecialEffect(weapon) {
  return weapon.damage > 0 || SPECIAL_WITHOUT_DAMAGE.includes(weapon.special);
}

